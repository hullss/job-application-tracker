export function translate(
    language: Language,
    key: string,
    values: TranslationValues = {},
) {
    const template =
        dictionaries[language][key] ?? dictionaries.en[key] ?? key

    return Object.entries(values).reduce(
        (message, [name, value]) =>
            message.replaceAll(`{{${name}}}`, String(value)),
        template,
    )
}
